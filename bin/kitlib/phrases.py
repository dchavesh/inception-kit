def table(language: str) -> dict:
    return PHRASES.get(str(language or FALLBACK), PHRASES[FALLBACK])


def has_table(language: str) -> bool:
    return str(language or FALLBACK) in PHRASES


def phrase(language: str, key: str, **values) -> str:
    text = table(language).get(key) or PHRASES[FALLBACK][key]
    return text.format(**values) if values else text

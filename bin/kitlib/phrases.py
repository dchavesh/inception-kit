from __future__ import annotations

FALLBACK = "en"

#: Marca de la línea de generación de toda vista derivada. La lleva el
#: renderizador y la filtran los comparadores: así una vista se compara con su
#: regeneración sin que la fecha del día produzca un falso «desactualizado», y
#: sin depender del idioma en que esté escrita la frase.
GENERATED_MARK = "<!-- generated -->"


def stamp(language: str, command: str, date: str, source: str) -> str:
    """La línea de generación de una vista derivada, marcada y en `language`."""
    return (f"*{phrase(language, 'derived-stamp', command=command, date=date, source=source)}*"
            f" {GENERATED_MARK}")


def without_stamp(text: str) -> str:
    """El texto de una vista menos sus líneas de generación."""
    return "\n".join(line for line in text.splitlines()
                     if GENERATED_MARK not in line).strip()

